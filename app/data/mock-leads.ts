export function createLeadFromForm(input: {
  category: string;
  city: string;
  country: string;
  description?: string;
  index: number;
}): Lead {
  const id = `gen-${Date.now()}-${input.index}`;
  return {
    id,
    businessName: `${input.category} Lead ${input.index + 1}`,
    category: input.category,
    city: input.city,
    country: input.country,
    email: `lead${input.index + 1}@${input.city.toLowerCase().replace(/\s+/g, "")}.example.com`,
    phone: `+1-555-01${String(input.index).padStart(2, "0")}`,
    description: input.description,
    contactChannel: "email",
    aiReview: baseReview(),
    outreach: baseOutreach(),
  };
}
